# Writes service-worker.js with the list of every app file to save for offline use.
# Run after changing files:  python3 tools-build-sw.py
import os, hashlib, json
root = os.path.dirname(os.path.abspath(__file__))
SKIP_DIRS = {"tests", "docs", "node_modules", ".git", ".github", "demo"}  # img/demo loads only when used
SKIP_FILES = {"service-worker.js", "package.json", "package-lock.json"}
files, h = [], hashlib.sha1()
for d, dirs, fs in os.walk(root):
    dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS and not x.startswith("."))
    for f in sorted(fs):
        rel = os.path.relpath(os.path.join(d, f), root).replace(os.sep, "/")
        if f.startswith(".") or rel in SKIP_FILES or rel.startswith("tools-") or rel.endswith((".py", ".md")):
            continue
        files.append("./" + rel)
        h.update(open(os.path.join(d, f), "rb").read())
files.sort()
version = h.hexdigest()[:10]
js = f"""// service-worker.js — saves the app's files so it opens offline. Generated by tools-build-sw.py.
const CACHE = "citizen-connect-{version}";
const FILES = {json.dumps(files)};

// Save every file on install.
self.addEventListener("install", (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
}});

// Remove old versions on activate.
self.addEventListener("activate", (e) => {{
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});

// Network first for our own files, so a reload always shows the latest version when online;
// the saved copy is used only when offline. Pages match without their ?id=… part.
self.addEventListener("fetch", (e) => {{
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    fetch(req).then((res) => {{
      if (res.ok && res.type === "basic") {{ const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }}
      return res;
    }}).catch(() => caches.match(req, {{ ignoreSearch: req.mode === "navigate" }})
      .then((hit) => hit || (req.mode === "navigate" ? caches.match("./index.html") : Response.error())))
  );
}});
"""
open(os.path.join(root, "service-worker.js"), "w").write(js)
print(len(files), "files, cache", version)
